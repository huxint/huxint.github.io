// Writes src/lib/stickers/glyphs.mjs: the outlines of every character used in
// a sticker caption, taken from Noto Sans CJK SC Black (SIL Open Font License).
// Captions are drawn from these outlines, so a meme looks the same on every
// system instead of depending on which heavy Chinese font is installed.
//
// Run it after adding or changing a caption:
//   node scripts/sticker-glyphs.mjs [path to NotoSansCJK-Black.ttc or .otf]
import { readFileSync, writeFileSync } from 'node:fs';
import { create } from 'fontkitten';
import { stickers } from '../src/lib/stickers/catalog.mjs';

const source =
  process.argv[2] ??
  process.env.STICKER_FONT ??
  '/usr/share/fonts/noto-cjk/NotoSansCJK-Black.ttc';
const file = create(readFileSync(source));
const font =
  'fonts' in file
    ? (file.fonts.find((face) => /CJKsc-/i.test(face.postscriptName)) ??
      file.fonts[0])
    : file;
const unit = 1000 / font.unitsPerEm;
const round = (value) => Math.round(value * unit);

// The outline with y pointing down and the baseline at 0. The first move is
// kept apart from the rest, which is written in relative commands, so a glyph
// is placed in a line by adding to that one point.
function outline(glyph) {
  let path = '';
  let start = null;
  let from = [0, 0];
  let open = [0, 0];
  const pair = (x, y) => `${x}${y < 0 ? '' : ' '}${y}`;
  for (const { command, args } of glyph.path.commands) {
    const points = [];
    for (let at = 0; at < args.length; at += 2)
      points.push([round(args[at]), -round(args[at + 1])]);
    const to = points.at(-1);
    if (command === 'moveTo') {
      if (start) path += `m${pair(to[0] - from[0], to[1] - from[1])}`;
      else start = to;
      open = to;
    } else if (command === 'lineTo') {
      const [dx, dy] = [to[0] - from[0], to[1] - from[1]];
      if (!dx && !dy) continue;
      path += dy === 0 ? `h${dx}` : dx === 0 ? `v${dy}` : `l${pair(dx, dy)}`;
    } else if (command === 'bezierCurveTo') {
      path +=
        'c' +
        points
          .map(([x, y]) => pair(x - from[0], y - from[1]))
          .join(' ')
          .replace(/ -/g, '-');
    } else if (command === 'quadraticCurveTo') {
      path +=
        'q' +
        points
          .map(([x, y]) => pair(x - from[0], y - from[1]))
          .join(' ')
          .replace(/ -/g, '-');
    } else if (command === 'closePath') {
      path += 'z';
      from = open;
      continue;
    }
    from = to;
  }
  return { start, path };
}

const characters = [
  ...new Set(stickers.flatMap((sticker) => [...(sticker.caption ?? '')])),
].sort();
const missing = [];
const rows = [];
for (const character of characters) {
  const glyph = font.glyphForCodePoint(character.codePointAt(0));
  if (!glyph || glyph.id === 0) {
    missing.push(character);
    continue;
  }
  const advance = round(glyph.advanceWidth);
  if (!glyph.path.commands.length) {
    rows.push(`  ${JSON.stringify(character)}: [${advance}],`);
    continue;
  }
  const { minX, maxX, minY } = glyph.bbox;
  const { start, path } = outline(glyph);
  rows.push(
    `  ${JSON.stringify(character)}: [${advance}, ${round(minX)}, ${round(maxX)}, ${Math.max(0, -round(minY))}, ${start[0]}, ${start[1]}, '${path}'],`,
  );
}
if (missing.length)
  throw new Error(
    `${font.postscriptName} has no glyph for: ${missing.join(' ')}`,
  );

writeFileSync(
  new URL('../src/lib/stickers/glyphs.mjs', import.meta.url),
  `// Generated by scripts/sticker-glyphs.mjs from ${font.postscriptName}; do not edit.
// Glyph outlines from Noto Sans CJK SC, Copyright 2014-2021 Adobe
// (http://www.adobe.com/), licensed under the SIL Open Font License 1.1.
//
// character: [advance, ink left, ink right, descent, start x, start y, path]
// in units of 1/1000 em, y pointing down from the baseline. A space has only
// its advance.
// prettier-ignore
export const CAPTION_GLYPHS = {
${rows.join('\n')}
};
`,
);
console.log(
  `${rows.length} glyphs from ${font.postscriptName} written to src/lib/stickers/glyphs.mjs`,
);
